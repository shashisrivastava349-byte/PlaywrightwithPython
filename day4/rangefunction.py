# range(num) if we give single number that will b considered as stopping point. In this case 0 is starting point
# range(starting,stoping)
# range(starting,stoping,step(inc/dec))

#Example 1: Only stopping point
print(list(range(10)))

#Example 2: starting and  stopping point
print(list(range(5,10)))

#Example 3: Print even Number between 1...10
print(list(range(0,10,2)))

#Example 4: Print odd Number between 1...10
print(list(range(1,10,2)))

#Example 5: reverse sequesnce
print(list(range(10,1,-1)))